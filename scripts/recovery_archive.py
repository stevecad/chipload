"""Private, authenticated recovery archives and consistent SQLite snapshots."""

import hashlib
import io
import json
import os
import re
import secrets
import shutil
import sqlite3
import stat
import subprocess
import tarfile
import tempfile
import time
from contextlib import ExitStack, closing
from pathlib import Path

from chipload.artifact import sdk_fingerprint
from chipload.project import unique_json

ROOT = Path(__file__).resolve().parents[1]
MAX_BYTES = 64 * 1024**3
STATE_FILES = {
    "deployment.json",
    "runtime.json",
    "client.json",
    "realm.json",
    "identity-ca.pem",
    "certificates/api.crt",
    "certificates/api.key",
    "certificates/identity.crt",
    "certificates/identity.key",
    "secrets/admin-password",
    "secrets/db-password",
    "secrets/agent-secret",
}
OPTIONAL_FILES = {
    "recovery/local-ca-key.pem",
    "restore.json",
    "credentials.json",
    "signing.json",
    "certificates.json",
}
DATA_FILES = {"data/chipload.db", "data/chipload.db.admission", "keycloak.dump"}
ALL_FILES = STATE_FILES | OPTIONAL_FILES | DATA_FILES


def private(path, *, directory=False):
    info = path.lstat()
    kind = stat.S_ISDIR if directory else stat.S_ISREG
    if not kind(info.st_mode) or info.st_uid != os.getuid() or info.st_mode & 0o077:
        raise ValueError(
            f"{path} must be an owner-only regular {'directory' if directory else 'file'}"
        )


def sync_directory(path):
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def sync_tree(root):
    for directory in sorted(
        (p for p in root.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True
    ):
        sync_directory(directory)
    sync_directory(root)


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "wb") as output:
        output.write(value.encode() if isinstance(value, str) else value)
        output.flush()
        os.fsync(output.fileno())


def replace_json(path, value):
    fd, name = tempfile.mkstemp(prefix=".update-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as output:
            json.dump(value, output, indent=2)
            output.flush()
            os.fsync(output.fileno())
        os.replace(name, path)
        sync_directory(path.parent)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def digest(path):
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def contract():
    # Restore at the backed-up runtime version; upgrades are a separate operation.
    paths = [
        ROOT / "uv.lock",
        *sorted((ROOT / "deploy/tls").glob("*")),
        *sorted((ROOT / "deploy/runtime").glob("*")),
    ]
    return {
        "sdk": sdk_fingerprint(),
        "deployment": hashlib.sha256(
            b"".join(p.name.encode() + b"\0" + p.read_bytes() + b"\0" for p in paths if p.is_file())
        ).hexdigest(),
    }


def generate_key(path):
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    private(path.parent, directory=True)
    write(path, secrets.token_hex(32) + "\n")
    sync_directory(path.parent)


def check_key(path):
    private(path.parent, directory=True)
    private(path)
    if not re.fullmatch(rb"[0-9a-f]{64}\n?", path.read_bytes()):
        raise ValueError("use a recovery key generated by tls-recovery keygen")


def crypt(source, target, key, *, decrypt=False, max_bytes=MAX_BYTES):
    """GnuPG owns the encryption format; no plaintext is consumed before GOODMDC."""
    check_key(key)
    private(source.parent, directory=True)
    private(target.parent, directory=True)
    private(source)
    if source.stat().st_size > max_bytes:
        raise ValueError("recovery archive exceeds the configured byte limit")
    if target.exists() or target.is_symlink():
        raise ValueError("archive output already exists")
    with tempfile.TemporaryDirectory(prefix=".gpg-", dir=target.parent) as temporary:
        directory = Path(temporary)
        command = [
            "gpg",
            "--homedir",
            temporary,
            "--no-options",
            "--batch",
            "--no-tty",
            "--no-autostart",
            "--no-symkey-cache",
            "--pinentry-mode",
            "loopback",
            "--passphrase-file",
            str(key),
            "--status-fd",
            "1",
            "--output",
            str(target),
        ]
        if decrypt:
            command += ["--max-output", str(max_bytes), "--decrypt", str(source)]
        else:
            # An explicit count avoids asking a gpg-agent to calibrate S2K.
            command += [
                "--s2k-count",
                "65011712",
                "--cipher-algo",
                "AES256",
                "--compress-algo",
                "none",
                "--symmetric",
                str(source),
            ]
        try:
            with (
                (directory / "status").open("wb") as status,
                (directory / "errors").open("wb") as errors,
            ):
                result = subprocess.run(command, stdout=status, stderr=errors, timeout=1800)
            with (directory / "status").open("rb") as status:
                messages = status.read(128 * 1024)
            if result.returncode or (
                decrypt
                and not all(
                    message in messages.splitlines()
                    for message in (b"[GNUPG:] GOODMDC", b"[GNUPG:] DECRYPTION_OKAY")
                )
            ):
                raise ValueError(
                    "archive authentication/decryption failed"
                    if decrypt
                    else "archive encryption failed"
                )
            target.chmod(0o600)
            if target.stat().st_size > max_bytes:
                raise ValueError("recovery archive exceeds the configured byte limit")
            with target.open("rb") as output:
                os.fsync(output.fileno())
        except BaseException:
            target.unlink(missing_ok=True)
            raise


def readonly(path):
    private(path)
    db = sqlite3.connect(path.absolute().as_uri() + "?mode=ro", uri=True, timeout=1)
    db.execute("PRAGMA trusted_schema=OFF")
    return db


def validate_pair(directory):
    with (
        closing(readonly(directory / "chipload.db")) as main,
        closing(readonly(directory / "chipload.db.admission")) as capacity,
    ):
        for db, version in ((main, 12), (capacity, 1)):
            if db.execute("PRAGMA user_version").fetchone()[0] != version:
                raise ValueError("unsupported recovery database schema")
            if db.execute("PRAGMA integrity_check").fetchall() != [("ok",)]:
                raise ValueError("recovery database integrity check failed")
            if db.execute("PRAGMA foreign_key_check").fetchone():
                raise ValueError("recovery database references are invalid")
        reference = main.execute("SELECT identity,state FROM admission_store WHERE id=1").fetchone()
        paired = capacity.execute("SELECT identity FROM admission_identity WHERE id=1").fetchone()
        if not reference or reference[1] != "ready" or paired != (reference[0],):
            raise ValueError("recovery databases are not a ready matched pair")
        if main.execute("SELECT 1 FROM builds WHERE state='running' LIMIT 1").fetchone():
            raise ValueError("running builds remain; finish or recover them before backup")
        if main.execute("SELECT 1 FROM worker_launches WHERE settled=0 LIMIT 1").fetchone():
            raise ValueError("unresolved container creation remains; keep its capacity reserved")
        if main.execute("SELECT 1 FROM executions WHERE state IN ('queued','running','indeterminate') LIMIT 1").fetchone():
            raise ValueError("unfinished operations remain; cancel, finish, or reconcile them before backup")
        if main.execute("SELECT 1 FROM python_runs WHERE state IN ('queued','running') LIMIT 1").fetchone():
            raise ValueError("unfinished Python runs remain; cancel or finish them before backup")


def snapshot_pair(source, destination):
    """Hold both writer locks while separate read connections back up WAL-aware snapshots."""
    destination.mkdir(mode=0o700)
    with ExitStack() as locks:
        for name in ("chipload.db", "chipload.db.admission"):
            path = source / name
            private(path)
            connection = locks.enter_context(
                closing(
                    sqlite3.connect(
                        path.absolute().as_uri() + "?mode=rw",
                        uri=True,
                        timeout=1,
                        isolation_level=None,
                    )
                )
            )
            connection.execute("BEGIN IMMEDIATE")
        validate_pair(source)
        for name in ("chipload.db", "chipload.db.admission"):
            write(destination / name, b"")
            deadline = time.monotonic() + 600

            def progress(*_):
                if time.monotonic() > deadline:
                    raise TimeoutError("SQLite backup exceeded its deadline")

            with (
                closing(readonly(source / name)) as original,
                closing(sqlite3.connect(destination / name)) as copy,
            ):
                original.backup(copy, pages=1024, progress=progress, sleep=0.05)
                copy.execute("PRAGMA journal_mode=DELETE")
        validate_pair(destination)


def pack(directory, target, metadata, *, max_bytes=MAX_BYTES):
    names = sorted(str(p.relative_to(directory)) for p in directory.rglob("*") if p.is_file())
    if not STATE_FILES | DATA_FILES <= set(names) or not set(names) <= ALL_FILES:
        raise ValueError("recovery set has missing or unexpected files")
    entries = {}
    total = 0
    for name in names:
        path = directory / name
        info = path.lstat()
        if not stat.S_ISREG(info.st_mode):
            raise ValueError("recovery set cannot contain links or special files")
        total += info.st_size
        if total > max_bytes:
            raise ValueError("recovery set exceeds the configured byte limit")
        entries[name] = {"size": info.st_size, "sha256": digest(path)}
    manifest = {**metadata, "version": 1, "contract": contract(), "files": entries}
    payload = json.dumps(manifest, sort_keys=True).encode()
    if len(payload) > 64 * 1024:
        raise ValueError("recovery manifest exceeds its limit")
    write(target, b"")
    with tarfile.open(target, "w", format=tarfile.PAX_FORMAT) as archive:
        header = tarfile.TarInfo("manifest.json")
        header.size, header.mode = len(payload), 0o600
        archive.addfile(header, io.BytesIO(payload))
        for name in names:
            path = directory / name
            header = tarfile.TarInfo(name)
            header.size, header.mode = entries[name]["size"], 0o600
            with path.open("rb") as source:
                archive.addfile(header, source)
    return manifest


def read_manifest(source):
    with tarfile.open(source, "r:") as archive:
        return manifest_header(archive)


def manifest_header(archive):
    first = archive.next()
    if (
        first is None
        or first.name != "manifest.json"
        or not first.isfile()
        or not 0 <= first.size <= 64 * 1024
    ):
        raise ValueError("missing or invalid recovery manifest")
    manifest = unique_json(archive.extractfile(first).read())
    if not isinstance(manifest, dict) or manifest.get("version") != 1:
        raise ValueError("unsupported recovery manifest")
    entries = manifest.get("files")
    if (
        not isinstance(entries, dict)
        or not (STATE_FILES | DATA_FILES) <= entries.keys()
        or not entries.keys() <= ALL_FILES
    ):
        raise ValueError("recovery manifest has missing or unexpected paths")
    for entry in entries.values():
        if (
            not isinstance(entry, dict)
            or type(entry.get("size")) is not int
            or entry["size"] < 0
            or not isinstance(entry.get("sha256"), str)
            or not re.fullmatch(r"[0-9a-f]{64}", entry["sha256"])
        ):
            raise ValueError("invalid recovery file metadata")
    return manifest


def unpack(source, destination, *, max_bytes=MAX_BYTES):
    """Read only fixed regular-file names; never apply archive paths, owners, or modes."""
    destination.mkdir(mode=0o700)
    with tarfile.open(source, "r:") as archive:
        manifest = manifest_header(archive)
        if manifest.get("contract") != contract():
            raise ValueError("recovery version differs; use the backed-up SDK/deployment checkout")
        entries = manifest["files"]
        total, seen = 0, set()
        members = iter(archive)
        next(members)  # Iteration includes the first header already read above.
        for member in members:
            if (
                not member.isfile()
                or member.name not in entries
                or member.name in seen
                or member.size < 0
            ):
                raise ValueError("invalid or repeated recovery member")
            entry = entries[member.name]
            if type(entry.get("size")) is not int or entry["size"] != member.size:
                raise ValueError("recovery member size disagrees with its manifest")
            total += member.size
            if total > max_bytes:
                raise ValueError("recovery set exceeds the configured byte limit")
            path = destination / member.name
            write(path, b"")
            with archive.extractfile(member) as incoming, path.open("wb") as output:
                shutil.copyfileobj(incoming, output, length=1024 * 1024)
                output.flush()
                os.fsync(output.fileno())
            if digest(path) != entry.get("sha256"):
                raise ValueError("recovery member digest disagrees with its manifest")
            seen.add(member.name)
        if seen != entries.keys():
            raise ValueError("recovery set is incomplete")
    validate_pair(destination / "data")
    return manifest
